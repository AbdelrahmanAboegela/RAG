"""GRPO advantages + masked PPO loss for a group of search rollouts.

    python code/examples/06_grpo.py
"""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from ragkit import group_relative_advantages, masked_policy_loss  # noqa: E402

if __name__ == "__main__":
    # 6 rollouts for the running example; reward = EM of the final answer (Search-R1).
    rollouts = [
        ("4 searches, answered 'no'", 1.0),
        ("2 searches, answered 'yes' (never looked up nationalities)", 0.0),
        ("5 searches, answered 'no'", 1.0),
        ("0 searches, answered 'yes'", 0.0),
        ("4 searches, answered 'no'", 1.0),
        ("3 searches, answered 'unknown'", 0.0),
    ]
    adv = group_relative_advantages([r for _, r in rollouts])
    for (desc, r), a in zip(rollouts, adv):
        print(f"reward={r:.0f}  advantage={a:+.2f}  {desc}")
    print("\nNo critic network: the group mean is the baseline. Note that the 4-search and the")
    print("5-search rollouts get the SAME advantage: outcome reward cannot see over-searching.")
    print("That is the gap AutoSearch / HiPRAG / StepSearch fill with process rewards.\n")

    # One rollout's tokens: 1 = generated by the policy, 0 = retrieved <information> text.
    mask = [1, 1, 1, 0, 0, 0, 0, 1, 1]
    logp_old = [-1.0] * 9
    logp_new = [-0.9, -0.8, -1.1, -5.0, -5.0, -5.0, -5.0, -0.7, -0.9]  # retrieved tokens look 'unlikely'
    print("masked loss  :", round(masked_policy_loss(logp_new, logp_old, adv[0], mask), 4))
    print("unmasked loss:", round(masked_policy_loss(logp_new, logp_old, adv[0], [1] * 9), 4),
          "<- the retriever's tokens now change the loss, though the policy never wrote them")
